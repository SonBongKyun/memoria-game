#!/usr/bin/env python3
"""Build only the new S353 normal and packed surface maps, from procedural fields.

No source albedo or model is opened. Atlas topology is the existing 4 x 4 grid:
8 upper tiles, then either repeated lower tiles (foes) or a protected head region
(ambient NPCs). Run --check to compare generated bytes without writing anything.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path

import numpy as np
from PIL import Image

VERSION = 1
TILE = 512
GUTTER = 8
INTERIOR = TILE - GUTTER * 2
PACKING = {"R": "ambient occlusion", "G": "roughness", "B": "metallic", "A": "mottled weathering mask"}
NORMAL_CONVENTION = "DirectX/Unreal tangent RGB; image y increases downward; unnormalized normal = (-dh/dx, +dh/dy, 1); neutral = (128,128,255)."

# UV tile semantics are deliberately explicit: these maps never infer a surface
# from painted albedo brightness or change the face/eye painting.
PROFILES = {
    "hero_detail": {"size": 512, "layout": "periodic shared detail", "tiles": ["hero"], "seed": 35301},
    "ambient_detail": {"size": 2048, "layout": "upper eight tiles; protected lower head half", "tiles": ["cloth", "leather", "cloth", "skin", "hair", "brass_soft", "leather", "cloth"], "seed": 35302},
    "husk_detail": {"size": 2048, "layout": "upper eight tiles repeated in lower half", "tiles": ["shreds", "bone_plate", "leather", "neutral", "void_face", "talon", "neutral", "crack"], "seed": 35303},
    "thief_detail": {"size": 2048, "layout": "upper eight tiles repeated in lower half", "tiles": ["cloth", "leather", "cloth", "skin", "eye_socket", "steel", "brass", "cloth"], "seed": 35304},
}
SURFACES = {
    # roughness, metallic, normal XY bound, roughness variation
    "hero":       (0.78, 0.00, 0.155, 0.065),
    "cloth":      (0.84, 0.00, 0.330, 0.060),
    "shreds":     (0.88, 0.00, 0.345, 0.055),
    "leather":    (0.63, 0.00, 0.300, 0.075),
    "skin":       (0.68, 0.00, 0.022, 0.014),
    "hair":       (0.78, 0.00, 0.045, 0.035),
    "brass_soft": (0.54, 0.45, 0.150, 0.035),
    "bone_plate": (0.65, 0.08, 0.340, 0.080),
    "neutral":    (0.80, 0.00, 0.035, 0.025),
    "void_face":  (0.96, 0.00, 0.008, 0.012),
    "talon":      (0.43, 0.05, 0.220, 0.055),
    "crack":      (0.80, 0.00, 0.060, 0.035),
    "eye_socket": (0.91, 0.00, 0.010, 0.014),
    "steel":      (0.40, 0.65, 0.160, 0.040),
    "brass":      (0.47, 0.70, 0.150, 0.040),
    "head":       (0.68, 0.00, 0.010, 0.008),
}
TAU = np.float32(np.pi * 2.0)


def grid(size: int) -> tuple[np.ndarray, np.ndarray]:
    axis = np.arange(size, dtype=np.float32) / size
    return np.meshgrid(axis, axis)


def wave(u: np.ndarray, v: np.ndarray, seed: int) -> np.ndarray:
    """Smooth periodic mottling; no white noise or pixel-scale checkerboard."""
    rng = np.random.Generator(np.random.PCG64(seed))
    out = np.zeros_like(u)
    total = 0.0
    for fx, fy, amplitude in ((1, 2, 1.0), (3, -1, 0.55), (5, 4, 0.24), (11, 7, 0.10)):
        phase = np.float32(rng.uniform(0, float(TAU)))
        out += np.float32(amplitude) * np.sin(TAU * (fx * u + fy * v) + phase)
        total += amplitude
    return out / np.float32(total)


def seam_field(u: np.ndarray, v: np.ndarray) -> np.ndarray:
    # Small raised side seams, broken into soft thread dashes. This field fades
    # before the gutter, avoiding strong normal jumps between adjacent tiles.
    rails = np.exp(-((u - 0.047) / 0.0055) ** 2) + np.exp(-((u - 0.953) / 0.0055) ** 2)
    stitches = np.maximum(0.0, np.cos(TAU * v * 28.0)) ** 3
    cross = np.exp(-((v - 0.855) / 0.0045) ** 2)
    return rails * (0.45 + 0.55 * stitches) + cross * 0.38


def height_field(kind: str, u: np.ndarray, v: np.ndarray, seed: int) -> np.ndarray:
    broad = wave(u, v, seed)
    grain = wave(u * 3.0, v * 3.0, seed + 101)
    if kind == "hero":
        # Completely periodic: safe for packed, differently oriented hero UVs.
        folds = 0.24 * np.sin(TAU * (3 * u + 0.10 * np.sin(TAU * v)))
        weave = 0.012 * (np.sin(TAU * 53 * u) + np.sin(TAU * 47 * v))
        return folds + 0.08 * broad + weave
    if kind in ("cloth", "shreds"):
        warp = 0.13 * np.sin(TAU * (v * 2.0 + 0.1))
        folds = 0.75 * np.sin(TAU * (u * 3.0 + warp)) + 0.24 * np.sin(TAU * (u * 7.0 - v))
        weave = 0.008 * (np.sin(TAU * u * 52.0) + np.sin(TAU * v * 48.0))
        if kind == "shreds":
            folds += 0.25 * np.sin(TAU * (u * 10.0 + 0.25 * np.sin(TAU * v * 3.0)))
        return folds + 0.12 * broad + weave + 0.16 * seam_field(u, v)
    if kind == "leather":
        wrinkles = 0.50 * np.sin(TAU * (v * 4.0 + 0.18 * np.sin(TAU * u * 2.0)))
        wrinkles += 0.20 * np.sin(TAU * (v * 9.0 - u * 2.0))
        return wrinkles + 0.15 * broad + 0.013 * grain + 0.17 * seam_field(u, v)
    if kind == "bone_plate":
        # Broad curved organic ridges and shallow hollows, not painted cracks.
        ridges = np.sin(TAU * (v * 5.0 + 0.19 * np.sin(TAU * u * 2.0)))
        ridges = np.sign(ridges) * np.abs(ridges) ** 1.6
        return 0.68 * ridges + 0.22 * broad + 0.08 * np.sin(TAU * (u * 7.0 + v))
    if kind in ("steel", "brass", "brass_soft"):
        return 0.035 * broad + 0.0035 * np.sin(TAU * v * 41.0) + 0.03 * np.sin(TAU * u * 2.0)
    if kind == "talon":
        return 0.45 * np.sin(TAU * (u * 4.0 + 0.15 * np.sin(TAU * v))) + 0.08 * broad
    if kind == "hair":
        return 0.10 * broad + 0.03 * np.sin(TAU * (u * 12.0 + v))
    # Almost flat skin/eye/void/head fields never invent facial features.
    return 0.10 * broad + 0.01 * grain


def normal_from_height(height: np.ndarray, bound: float, periodic: bool) -> np.ndarray:
    """Bound XY after normalization, preserving the relative field frequencies."""
    if periodic:
        dx = (np.roll(height, -1, axis=1) - np.roll(height, 1, axis=1)) * 0.5
        dy = (np.roll(height, -1, axis=0) - np.roll(height, 1, axis=0)) * 0.5
    else:
        dy, dx = np.gradient(height)
    length = np.sqrt(dx * dx + dy * dy)
    maximum = float(length.max())
    slope_bound = bound / np.sqrt(1.0 - bound * bound)
    scale = np.float32(slope_bound / maximum) if maximum else np.float32(0)
    nx, ny = -dx * scale, dy * scale
    nz = np.ones_like(nx)
    inv_length = 1.0 / np.sqrt(nx * nx + ny * ny + nz * nz)
    return np.stack((nx * inv_length, ny * inv_length, nz * inv_length), axis=2)


def quantize(values: np.ndarray) -> np.ndarray:
    return np.rint(np.clip(values, 0.0, 1.0) * 255.0).astype(np.uint8)


def make_tile(kind: str, seed: int, periodic: bool = False) -> tuple[np.ndarray, np.ndarray]:
    size = TILE if periodic else INTERIOR
    u, v = grid(size)
    roughness, metallic, normal_bound, rough_variation = SURFACES[kind]
    height = height_field(kind, u, v, seed)
    mottling = wave(u, v, seed + 307)
    if not periodic:
        # Smooth fade within 24 pixels of the UV interior edge. Constant-height
        # gutters are extruded afterward, so minification does not borrow from
        # a neighbor with another surface type.
        edge = np.minimum.reduce((u, v, 1.0 - u, 1.0 - v))
        fade = np.clip(edge / (24.0 / size), 0.0, 1.0)
        fade = fade * fade * (3.0 - 2.0 * fade)
        height *= fade
    normal = normal_from_height(height, normal_bound, periodic)
    h_span = max(float(np.max(np.abs(height))), 1e-6)
    crevices = np.clip(-height / h_span, 0.0, 1.0)
    ao = np.clip(0.990 - 0.035 * crevices + 0.006 * mottling, 0.93, 1.0)
    if kind in ("skin", "head", "eye_socket", "void_face"):
        ao = np.full_like(u, 0.996)
    rough = np.clip(roughness + rough_variation * mottling + crevices * 0.018, 0.25, 0.99)
    metal = np.full_like(u, metallic)
    weather = np.clip(0.48 + 0.38 * mottling + 0.10 * crevices, 0.0, 1.0)
    packed = np.stack((ao, rough, metal, weather), axis=2)
    normal_bytes = quantize(normal * 0.5 + 0.5)
    packed_bytes = quantize(packed)
    if not periodic:
        normal_bytes = np.pad(normal_bytes, ((GUTTER, GUTTER), (GUTTER, GUTTER), (0, 0)), mode="edge")
        packed_bytes = np.pad(packed_bytes, ((GUTTER, GUTTER), (GUTTER, GUTTER), (0, 0)), mode="edge")
    return normal_bytes, packed_bytes


def generate_profile(name: str) -> tuple[np.ndarray, np.ndarray]:
    profile = PROFILES[name]
    if name == "hero_detail":
        return make_tile("hero", profile["seed"], periodic=True)
    normals = np.zeros((2048, 2048, 3), dtype=np.uint8)
    surfaces = np.zeros((2048, 2048, 4), dtype=np.uint8)
    for index, kind in enumerate(profile["tiles"]):
        normal, surface = make_tile(kind, profile["seed"] + index * 37)
        x, y = index % 4 * TILE, index // 4 * TILE
        normals[y:y + TILE, x:x + TILE] = normal
        surfaces[y:y + TILE, x:x + TILE] = surface
    if name == "ambient_detail":
        # Existing lower-half painted heads are unrelated to upper body UV
        # semantics; use only a nearly flat, non-metallic neutral response.
        for index in range(8):
            normal, surface = make_tile("head", profile["seed"] + 1000 + index * 37)
            x, y = index % 4 * TILE, (index // 4 + 2) * TILE
            normals[y:y + TILE, x:x + TILE] = normal
            surfaces[y:y + TILE, x:x + TILE] = surface
    else:
        normals[1024:] = normals[:1024]
        surfaces[1024:] = surfaces[:1024]
    return normals, surfaces


def png_bytes(array: np.ndarray) -> bytes:
    output = io.BytesIO()
    Image.fromarray(array).save(output, format="PNG", compress_level=9, optimize=False)
    return output.getvalue()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def describe(name: str, normal: np.ndarray, surface: np.ndarray) -> dict:
    decoded = normal.astype(np.float32) / 255.0 * 2.0 - 1.0
    xy = np.linalg.norm(decoded[:, :, :2], axis=2)
    result = {
        "normal_xy_max_encoded": round(float(xy.max()), 6),
        "normal_xy_mean_encoded": round(float(xy.mean()), 6),
        "surface_channel_min": [int(x) for x in surface.min(axis=(0, 1))],
        "surface_channel_max": [int(x) for x in surface.max(axis=(0, 1))],
    }
    if name == "hero_detail":
        # Endpoints differ by one texel in a truly periodic sampled field.
        result["periodic_edge_byte_delta_max"] = max(int(np.abs(normal[0].astype(int) - normal[-1].astype(int)).max()), int(np.abs(normal[:, 0].astype(int) - normal[:, -1].astype(int)).max()))
    if name != "hero_detail":
        result["tile_profiles"] = [
            {"tile": i, "surface": kind, "roughness": SURFACES[kind][0], "metallic": SURFACES[kind][1], "normal_xy_limit": SURFACES[kind][2]}
            for i, kind in enumerate(PROFILES[name]["tiles"])
        ]
        result["lower_half"] = "protected head: roughness .68, metallic 0, normal XY <= .01" if name == "ambient_detail" else "byte-identical to upper half"
    return result


def validate(name: str, normal: np.ndarray, surface: np.ndarray) -> None:
    size = PROFILES[name]["size"]
    if normal.shape != (size, size, 3) or surface.shape != (size, size, 4):
        raise AssertionError(f"Wrong dimensions for {name}")
    if int(surface[:, :, 0].min()) < 237:  # .93 rounded to 8 bit
        raise AssertionError(f"AO outside restrained range for {name}")
    decoded = normal.astype(np.float32) / 255.0 * 2.0 - 1.0
    if float(np.linalg.norm(decoded[:, :, :2], axis=2).max()) > (0.162 if name == "hero_detail" else 0.354):
        raise AssertionError(f"Normal amplitude exceeded for {name}")
    if int(normal[:, :, 2].min()) < 246:
        raise AssertionError(f"Normal points too far from surface for {name}")
    if name == "ambient_detail":
        if np.any(surface[1024:, :, 2]):
            raise AssertionError("Protected ambient head acquired a metallic response")
        if float(np.linalg.norm(decoded[1024:, :, :2], axis=2).max()) > 0.017:
            raise AssertionError("Protected ambient head normal is too strong")
    if name in ("husk_detail", "thief_detail"):
        if not np.array_equal(normal[:1024], normal[1024:]) or not np.array_equal(surface[:1024], surface[1024:]):
            raise AssertionError("Monster lower atlas half does not match source UV topology")


def payloads() -> tuple[dict[str, bytes], dict]:
    files: dict[str, bytes] = {}
    manifest = {
        "schema": "memoria.surface_detail.s353.v1",
        "generator_version": VERSION,
        "generator_sha256": sha256(Path(__file__).read_bytes()),
        "source_images_read": [],
        "normal_convention": NORMAL_CONVENTION,
        "surface_packing": PACKING,
        "texture_import": {"normal": {"srgb": False, "compression": "TC_Normalmap", "flip_green": False}, "surface": {"srgb": False, "compression": "TC_Masks"}},
        "atlas": {"tile_px": TILE, "gutter_px": GUTTER, "interior_px": INTERIOR, "normal_fade_px": 24},
        "profiles": {},
        "files": {},
    }
    for name in PROFILES:
        normal, surface = generate_profile(name)
        validate(name, normal, surface)
        manifest["profiles"][name] = {**PROFILES[name], **describe(name, normal, surface)}
        for suffix, data in (("normal", normal), ("surface", surface)):
            filename = f"{name}_{suffix}.png"
            encoded = png_bytes(data)
            files[filename] = encoded
            manifest["files"][filename] = {"sha256": sha256(encoded), "bytes": len(encoded), "mode": "RGB" if suffix == "normal" else "RGBA", "dimensions": [data.shape[1], data.shape[0]]}
    files["surface_detail_s353_manifest.json"] = (json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return files, manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1] / "ArtSource" / "SurfaceDetail")
    parser.add_argument("--check", action="store_true", help="Regenerate in memory and compare exact PNG/manifest bytes; do not write.")
    args = parser.parse_args()
    files, manifest = payloads()
    if args.check:
        missing = [name for name in files if not (args.output_dir / name).is_file()]
        changed = [name for name, data in files.items() if (args.output_dir / name).is_file() and (args.output_dir / name).read_bytes() != data]
        if missing or changed:
            print(json.dumps({"result": "FAIL", "missing": missing, "changed": changed}, ensure_ascii=False))
            return 1
        print(json.dumps({"result": "PASS", "files": len(files), "pngs": len(manifest["files"]), "source_images_read": [], "checks": "exact deterministic bytes, dimensions, normal bounds, AO bounds, atlas topology, protected head"}))
        return 0
    args.output_dir.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (args.output_dir / name).write_bytes(data)
    print(json.dumps({"result": "GENERATED", "output_dir": str(args.output_dir.resolve()), "pngs": len(manifest["files"]), "profiles": {name: info["normal_xy_max_encoded"] for name, info in manifest["profiles"].items()}}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
